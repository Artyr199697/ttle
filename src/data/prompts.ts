/**
 * Заменяет плейсхолдеры в промпте на реальные значения
 */
export function fillPrompt(promptTemplate: string, replacements: Record<string, string>): string {
  let result = promptTemplate;
  for (const [key, value] of Object.entries(replacements)) {
    result = result.replace(`{{${key}}}`, value);
  }
  return result;
}
